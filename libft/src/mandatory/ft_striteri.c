#include "libft.h"

size_t	ft_strlen(const char *s);

/*applies function f to each character of string s in place.*/

void	ft_striteri(char *s, void (*f)(unsigned int, char*))
{
	size_t	i;

	if (!s || !f)
		return ;
	i = 0;
	while (s[i])
	{
		f(i, &s[i]);
		i++;
	}
}
